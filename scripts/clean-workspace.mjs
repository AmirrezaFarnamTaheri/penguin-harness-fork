#!/usr/bin/env node
/**
 * clean-workspace.mjs — find (and optionally remove) the build and test debris an agent run
 * leaves in this repository.
 *
 * WHY THIS EXISTS. The product is developed by agents working in this tree, and every run leaves
 * something behind: a `test-results/` from a Playwright invocation, a `dist/` from a build, a
 * `target/` from a Rust compile, a `.vite` dep cache, a `_probe*.spec.mjs` written to poke at a
 * one-off question, a screenshot dumped to prove something was rendered. None of it is tracked,
 * so it never shows up in `git status` as clutter, and none of it is removed by any later command.
 * It is also not small: a single `target/` or a set of `dist/` directories is hundreds of
 * megabytes, and the accumulation is across sessions rather than within one. This has already
 * caused a real incident here, and a cleaner that only exists as a rule in prose does not prevent
 * it — the rule has to be executable at the moment the agent is about to declare itself done.
 *
 * WHAT IT WILL NEVER DO.
 *   - Delete anything tracked by git. `git ls-files` is consulted first and a candidate that
 *     contains any tracked path is refused and reported as `protected:tracked`. This is the whole
 *     safety argument: a build directory that someone has checked in must survive a cleanup.
 *   - Delete anything in `NEVER_TOUCH` (below) even when untracked. "Untracked" is not the same as
 *     "disposable" — `/AGENTS.md`, `/design` and `/CLAUDE.md` are gitignored local files that are
 *     supposed to be there, and `.data/` is a user's data root, not an artifact.
 *
 * MODES. Default is REPORT ONLY: it lists what it found and changes nothing. `--apply` deletes.
 * There is no mode that deletes without asking for `--apply` explicitly.
 *
 *   node scripts/clean-workspace.mjs                    # report
 *   node scripts/clean-workspace.mjs --apply            # delete the always-on classes
 *   node scripts/clean-workspace.mjs --include-dist     # also offer dist/ (opt-in)
 *   node scripts/clean-workspace.mjs --include-target   # also offer Rust target/ (opt-in)
 *   node scripts/clean-workspace.mjs --json             # machine-readable report
 *
 * WHY `dist/` AND `target/` ARE OPT-IN. Both are rebuildable but not free — a `target/` in
 * particular is a deliberate warm cache that a Rust build can spend minutes recreating. Deleting
 * someone's cache to tidy their disk is a trade they did not ask for, so the script shows the size
 * and leaves the decision to the caller. The always-on classes (test output, dep caches, scratch
 * files) have no such value: they are pure waste.
 */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

/**
 * Directory basenames that are cleanup candidates, by class.
 *
 * `always` classes are pure waste and are removed by `--apply`. `optIn` classes are expensive to
 * rebuild, so they are only even considered when their flag is passed.
 */
export const TARGET_CLASSES = {
  playwright: {
    kind: "dir",
    always: true,
    label: "Playwright run output",
    reason:
      "Per-run test output. Regenerated by the next test run; keeping it only confuses the next one.",
  },
  viteCache: {
    kind: "dir",
    always: true,
    label: "Vite dependency cache",
    reason: "Rebuilt on the next dev server start.",
  },
  build: {
    kind: "dir",
    always: false,
    label: "Build output",
    reason: "Rebuildable, but the next build pays for it. Opt-in so a warm dist survives.",
  },
  rust: {
    kind: "dir",
    always: false,
    label: "Rust build directory",
    reason: "Very expensive to rebuild. Opt-in only; often a deliberate warm cache.",
  },
  scratch: {
    kind: "file",
    always: true,
    label: "Scratch debug spec",
    reason: "A one-off spec written to probe a question. Never part of a suite.",
  },
  screenshot: {
    kind: "file",
    always: true,
    label: "Scratch screenshot",
    reason: "Dumped to show something rendered once. Not a committed asset.",
  },
};

/**
 * Paths that are never candidates, whatever their state. Matched against repo-relative paths.
 *
 * `.data/` is a user's data root and `JEV-Family/` is a checked-out external reference tree: both
 * are ignored by git precisely so that they are invisible to tooling, which makes them exactly
 * the kind of thing an over-eager recursive delete destroys silently. `.agents/` holds the skill
 * library and `assets/`/`docs/` hold real committed content; they are listed so that a future
 * broad rule cannot quietly widen into them.
 */
export const NEVER_TOUCH = new Set([
  ".git",
  ".data",
  ".agents",
  "AGENTS.md",
  "CLAUDE.md",
  "design",
  "JEV-Family",
  "assets",
  "docs",
  "node_modules",
]);

/**
 * Directories that are never descended into. Cleanup looks for debris; it does not go looking
 * through dependency trees or vendored trees, where a `dist/` belongs to a third party.
 */
const SKIP_DIRS = new Set([
  ".git",
  "node_modules",
  ".data",
  ".agents",
  "JEV-Family",
  "src",
  "test",
  "tests",
]);

/** Screenshot dumps are only debris in the places an agent actually dumps them. */
const SCREENSHOT_DIRS = ["audit-evidence", "artifacts", "debug", "."];

/**
 * The set of repo-relative paths git tracks, used to refuse deleting anything checked in.
 * Returns null when git cannot answer, which the caller treats as "do not delete anything".
 */
export function readTrackedFiles(root) {
  const res = spawnSync("git", ["ls-files", "-z"], {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
    windowsHide: true,
  });
  if (res.error || res.status !== 0 || typeof res.stdout !== "string") return null;
  return new Set(
    res.stdout
      .split("\0")
      .map((p) => p.trim().replace(/\\/g, "/"))
      .filter(Boolean),
  );
}

/** Whether `rel` is, or contains, a tracked path. A tracked file blocks its whole directory. */
export function containsTracked(rel, tracked) {
  if (tracked === null) return true; // Unknown -> assume protected.
  const dir = rel.endsWith("/") ? rel : `${rel}/`;
  for (const p of tracked) {
    if (p === rel || p.startsWith(dir)) return true;
  }
  return false;
}

/** Whether any path segment of `rel` is a never-touch name. */
export function isNeverTouch(rel) {
  return rel
    .split("/")
    .filter(Boolean)
    .some((seg) => NEVER_TOUCH.has(seg));
}

function dirSizeBytes(dir) {
  let total = 0;
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return 0;
  }
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) total += dirSizeBytes(full);
    else {
      try {
        total += fs.statSync(full).size;
      } catch {
        // Vanished mid-walk; contributes nothing.
      }
    }
  }
  return total;
}

export function humanSize(bytes) {
  if (bytes < 1024) return `${bytes} B`;
  const units = ["KiB", "MiB", "GiB", "TiB"];
  let value = bytes / 1024;
  let unit = 0;
  while (value >= 1024 && unit < units.length - 1) {
    value /= 1024;
    unit += 1;
  }
  return `${value.toFixed(1)} ${units[unit]}`;
}

/**
 * Collects the dep caches sitting directly in one `node_modules` directory.
 *
 * Only the immediate children are read. A package's own nested `node_modules` belongs to its
 * dependencies, not to the agent that ran the build, and deleting a dependency's cache is
 * another project's decision.
 */
function collectDepCaches(nodeModulesDir, nodeModulesRel, out) {
  let entries;
  try {
    entries = fs.readdirSync(nodeModulesDir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    if (entry.name !== ".vite" && entry.name !== ".cache") continue;
    out.push({
      rel: `${nodeModulesRel}/${entry.name}`,
      className: "viteCache",
      type: "dir",
    });
  }
}

/**
 * Walks `dir` collecting cleanup candidates. Returns repo-relative paths.
 *
 * `walkDepth` bounds the search: the debris that matters sits at known, shallow depths, and an
 * unbounded walk of a monorepo is how a cleanup tool ends up spending a minute statting a
 * dependency tree it was never going to delete.
 */
function walk(dir, root, opts, out, depth = 0) {
  if (depth > (opts.maxDepth ?? 6)) return;
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    const rel = path.relative(root, full).replace(/\\/g, "/");
    // `node_modules` is never a candidate and is never descended into - but the dep caches
    // immediately inside it are a common source of leftover disk, so they are collected one
    // level down here, and the walk still stops at the dependency-tree boundary.
    if (entry.isDirectory() && entry.name === "node_modules" && !rel.includes("/node_modules")) {
      collectDepCaches(full, rel, out);
      continue;
    }
    if (isNeverTouch(rel)) continue;

    if (entry.isDirectory()) {
      if (entry.name === "test-results" || entry.name === "playwright-report") {
        out.push({ rel, className: "playwright", type: "dir" });
        continue; // Do not descend into an output directory to find output.
      }
      if (entry.name === "dist") {
        if (opts.includeDist) out.push({ rel, className: "build", type: "dir" });
        continue;
      }
      if (entry.name === "target") {
        if (opts.includeTarget) out.push({ rel, className: "rust", type: "dir" });
        continue;
      }
      if (
        (entry.name === ".vite" || entry.name === ".cache") &&
        rel.split("/").includes("node_modules")
      ) {
        out.push({ rel, className: "viteCache", type: "dir" });
        continue;
      }
      if (SKIP_DIRS.has(entry.name)) continue;
      walk(full, root, opts, out, depth + 1);
      continue;
    }

    if (!entry.isFile()) continue;
    if (/^_?probe.*\.spec\.mjs$/.test(entry.name)) {
      out.push({ rel, className: "scratch", type: "file" });
      continue;
    }
    if (entry.name.endsWith(".png") && SCREENSHOT_DIRS.includes(path.dirname(rel))) {
      out.push({ rel, className: "screenshot", type: "file" });
    }
  }
}

/**
 * Builds the full report. `apply` is deliberately not a parameter of the scan: the same scan
 * drives both modes, so what `--apply` deletes is exactly what the default report showed.
 */
export function scan(root, options = {}) {
  const opts = { includeDist: false, includeTarget: false, maxDepth: 6, ...options };
  const tracked = options.tracked !== undefined ? options.tracked : readTrackedFiles(root);

  const found = [];
  walk(root, root, opts, found);

  const items = found.map((candidate) => {
    const spec = TARGET_CLASSES[candidate.className];
    const abs = path.join(root, candidate.rel);
    const protectedByGit = containsTracked(candidate.rel, tracked);
    return {
      path: candidate.rel,
      class: candidate.className,
      type: candidate.type,
      label: spec.label,
      reason: spec.reason,
      optIn: spec.always === false,
      bytes: candidate.type === "dir" ? dirSizeBytes(abs) : safeSize(abs),
      protected: protectedByGit ? "tracked" : null,
    };
  });

  items.sort((a, b) => b.bytes - a.bytes);
  return {
    root,
    gitAvailable: tracked !== null,
    items,
    totalBytes: items.reduce((sum, i) => sum + i.bytes, 0),
    // An opt-in class only ever reaches `items` when its flag was passed (the walk gates on
    // it), so "removable" reduces to "not protected by git" — no second flag check needed.
    removable: items.filter((i) => !i.protected),
  };
}

function safeSize(abs) {
  try {
    return fs.statSync(abs).size;
  } catch {
    return 0;
  }
}

/** Deletes the removable items. Refuses protected ones again here, so a caller cannot bypass it. */
export function applyClean(root, report) {
  const removed = [];
  const refused = [];
  for (const item of report.removable) {
    if (item.protected) {
      refused.push(item);
      continue;
    }
    const abs = path.join(root, item.path);
    try {
      fs.rmSync(abs, { recursive: true, force: true });
      removed.push(item);
    } catch (err) {
      refused.push({ ...item, protected: `unremovable:${err.code ?? "unknown"}` });
    }
  }
  return { removed, refused };
}

function parseArgs(argv) {
  const opts = { apply: false, json: false, includeDist: false, includeTarget: false, help: false };
  for (const arg of argv) {
    if (arg === "--") continue;
    else if (arg === "--apply") opts.apply = true;
    else if (arg === "--json") opts.json = true;
    else if (arg === "--include-dist") opts.includeDist = true;
    else if (arg === "--include-target") opts.includeTarget = true;
    else if (arg === "--help" || arg === "-h") opts.help = true;
    else throw new Error(`Unknown argument: ${arg}`);
  }
  return opts;
}

const USAGE = `Usage: node scripts/clean-workspace.mjs [--apply] [--include-dist] [--include-target] [--json]

Reports by default; deletes only with --apply.
  --include-dist    also consider dist/ directories (rebuildable, not free)
  --include-target  also consider Rust target/ directories (very expensive to rebuild)
  --json            machine-readable output
`;

export function main(argv, { root, log = console.log, error = console.error } = {}) {
  let opts;
  try {
    opts = parseArgs(argv);
  } catch (err) {
    error(String(err.message));
    error(USAGE);
    return 2;
  }
  if (opts.help) {
    log(USAGE);
    return 0;
  }

  const repoRoot = root ?? process.cwd();
  const report = scan(repoRoot, opts);

  if (!report.gitAvailable) {
    error("Refusing to continue: `git ls-files` did not answer, so nothing can be proven safe.");
    error("Run this inside the repository, or clean by hand.");
    return 1;
  }

  const result = opts.apply ? applyClean(repoRoot, report) : { removed: [], refused: [] };

  if (opts.json) {
    log(
      JSON.stringify(
        { mode: opts.apply ? "apply" : "report", root: repoRoot, ...report, result },
        null,
        2,
      ),
    );
    return 0;
  }

  const refusedItems = report.items.filter((i) => i.protected);
  // In apply mode the removable set is what was just removed; in report mode it is what would be.
  const shown = result.removed.length > 0 ? result.removed : report.removable;
  if (shown.length === 0 && refusedItems.length === 0) {
    log(
      "  Nothing to clean. (--include-dist / --include-target also offer the rebuildable caches.)\n",
    );
    return 0;
  }

  log(
    `\n  Workspace cleanup — ${opts.apply ? "APPLIED" : "REPORT ONLY (pass --apply to delete)"}\n`,
  );
  for (const item of [...shown, ...refusedItems]) {
    const mark = item.protected
      ? "  REFUSED  "
      : result.removed.includes(item)
        ? "  removed "
        : "  would remove";
    const why = item.protected ? "tracked by git, so never deleted" : item.reason;
    log(`${mark}  ${humanSize(item.bytes).padStart(9)}  ${item.path}`);
    log(`              ${item.label} - ${why}`);
  }

  const totalBytes =
    result.removed.length > 0
      ? result.removed.reduce((s, i) => s + i.bytes, 0)
      : shown.reduce((s, i) => s + i.bytes, 0);
  const verb = result.removed.length > 0 ? "Removed" : "Found";
  log(`\n  ${verb} ${shown.length} item(s), ${humanSize(totalBytes)} total.`);
  if (refusedItems.length > 0) {
    log(`  ${refusedItems.length} item(s) refused: git tracks them.`);
  }
  log("");
  return 0;
}

// fileURLToPath, not URL.pathname: on Windows a file URL's pathname is "/D:/repo/x.mjs" with a
// leading slash, so comparing it to process.argv[1] ("D:\repo\x.mjs") never matches and the
// script silently does nothing when run directly.
const invokedDirectly =
  process.argv[1] !== undefined &&
  path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));
if (invokedDirectly) {
  process.exitCode = main(process.argv.slice(2), { root: process.cwd() });
}
